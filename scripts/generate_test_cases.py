def _load_policy(policy_no: str) -> dict:
    """Vehicle facts come from data/policies.csv — the single source of truth.
    Hardcoded regs drifted once before (Case 3 shipped a stale DL-05 plate that
    made FC-20 fire an unintended FIR-vehicle mismatch)."""
    with open(ROOT / "data" / "policies.csv", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["policy_no"] == policy_no:
                return row
    raise SystemExit(f"policy {policy_no} not found in data/policies.csv")


def _fmt_reg(reg: str) -> str:
    """MH28BQ2255 -> MH-28-BQ-2255 (display format used on FIRs/estimates)."""
    r = reg.replace("-", "").replace(" ", "").upper()
    out, groups = [], []
    i = 0
    while i < len(r):
        j = i
        is_digit = r[i].isdigit()
        while j < len(r) and r[j].isdigit() == is_digit:
            j += 1
        groups.append(r[i:j])
        i = j
    return "-".join(groups)

# GST on an Indian repair invoice, split into its two intra-state halves.
# GST 2.0 (22-Sep-2025) collapsed the slabs to 5/18/40; auto parts (HSN 8708)
# and repair labour are BOTH 18%, so one flat rate across parts and labour is
# correct. data_sanity cross-checks this against settlement_calc.GST_RATE —
# fixtures that tax differently from the payout engine are a silent trap.
# Provenance. These fixtures reproduce real Indian document layouts closely
# enough to be convincing, so every one of them says what it is. Kept to a
# single small footer line rather than a watermark across the content: the
# document-authenticity pass reads the IMAGE and feeds FC-28 (a 30-point check),
# and changelog item 26c records a prior false positive raised by exactly this
# kind of disclosure text. The same string also goes into the PDF metadata, so a
# file inspection shows it even if the render is cropped.
SPECIMEN_LINE = ("SYNTHETIC SPECIMEN - generated by ClaimIntel for demonstration. "
                 "Not a genuine commercial document.")

CGST_RATE = 0.09
SGST_RATE = 0.09

DARK_GREEN = (27, 94, 58)
LIGHT_GREEN_BG = (235, 245, 238)
DARK_BLUE = (17, 62, 110)
LIGHT_BLUE_BG = (223, 236, 249)
GREY_TEXT = (90, 90, 90)


def _s(text: str) -> str:
    """fpdf2 core fonts are Latin-1 only — sanitize any non-Latin-1 characters."""
    return (
        text.replace("–", "-").replace("—", "-")
        .replace("'", "'").replace("'", "'")
        .replace(""", '"').replace(""", '"')
        .encode("latin-1", "replace").decode("latin-1")
    )


def _ref_date(argv: list[str]) -> date:
    if len(argv) > 1:
        return datetime.strptime(argv[1], "%Y-%m-%d").date()
    return date.today()


def _section_bar(pdf: FPDF, text: str, rgb):
    pdf.set_fill_color(*rgb)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 7, _s(text), fill=True, new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(1)


def _field(pdf: FPDF, label: str, value: str):
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*GREY_TEXT)
    pdf.cell(0, 5, _s(label), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 6, _s(value), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(1)


