"""
OEM price catalogue — the first tier of ClaimIntel's part pricing.

WHY IT EXISTS
Part prices used to come from a live web search on every investigation, cached
for 30 days in a gitignored file. Two problems, both measured on the demo
claims: the same part came back at different prices on different runs (an
Innova Crysta headlamp at Rs.24,700 on the left and Rs.11,500 on the right —
the same component), and a fresh clone had no prices at all until it had spent
API quota re-discovering them.

WHAT IT IS — AND IS NOT
A committed JSON file (config.OEM_CATALOG_PATH) of vehicle -> part -> price,
with the lowest and highest price the corroborating retailers showed and the
date it was fetched. Every figure in it came from the SAME Serper/Tavily API
and the same >=2-independent-domain corroboration rule as the live lookup —
filled by dev/scripts/build_oem_catalog.py and written back by the pricing
engine whenever an investigation prices a part live. Nothing in it is typed in
by hand. That is the difference from the static catalogue removed on
2026-08-13, which was fabricated demo data (see pricing_engine's docstring).

FRESHNESS
An entry is valid for OEM_CATALOG_TTL_DAYS (90). Older than that, the pricing
engine re-fetches it from the API and overwrites it. If the re-fetch fails
(offline, quota, no corroboration today) the old price is still used, but
flagged `stale` with its fetch date on every surface that shows it — a real
price from four months ago beats no price, as long as nobody is misled about
its age.

Keys: vehicle = price_lookup._vehicle_query_name(vehicle).lower() (make +
model, no trim or registration — the same key the price cache uses); part =
the canonical name from pricing_engine._canon(), which callers pass in.
"""

import copy
import json
import os
import tempfile
import threading
from datetime import datetime, timedelta, timezone
from typing import Optional

try:
    from config import OEM_CATALOG_PATH, OEM_CATALOG_TTL_DAYS
except Exception:      # importable standalone (tests, scripts) without .env
    OEM_CATALOG_PATH = os.path.join(
        os.path.dirname(__file__), "..", "..", "data", "config", "oem_price_catalog.json")
    OEM_CATALOG_TTL_DAYS = 90

SCHEMA_VERSION = 1
_IST = timezone(timedelta(hours=5, minutes=30))

_NOTE = (
    "Market part prices fetched from the Serper/Tavily search API — a price is only "
    "recorded when >=2 independent retailer domains corroborate it. Not hand-entered. "
    "Generated by dev/scripts/build_oem_catalog.py and refreshed at investigation time; "
    "entries older than ttl_days are re-fetched before use."
)

# pricing_engine prices up to 8 parts concurrently and each may write back, so
# every read-modify-write of the in-memory catalogue and every save holds this.
# Re-entrant because upsert() saves while already holding it.
_lock = threading.RLock()
_catalog: Optional[dict] = None
_loaded_from: Optional[str] = None
# A file that exists but will not parse must never be overwritten by the next
# write-back — that would replace the whole catalogue with one entry.
_writable = True


def _empty() -> dict:
    return {"schema_version": SCHEMA_VERSION, "ttl_days": OEM_CATALOG_TTL_DAYS,
            "note": _NOTE, "vehicles": {}}


def _load() -> dict:
    """The in-memory catalogue, (re)loaded when the configured path changes."""
    global _catalog, _loaded_from, _writable
    with _lock:
        path = OEM_CATALOG_PATH
        if _catalog is None or _loaded_from != path:
            _writable = True
            try:
                with open(path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                if not isinstance(data, dict) or not isinstance(data.get("vehicles"), dict):
                    raise ValueError("no 'vehicles' object")
                _catalog = data
            except FileNotFoundError:
                _catalog = _empty()
            except Exception:
                _catalog = _empty()
                _writable = False
            _loaded_from = path
        return _catalog


def reload() -> None:
    """Drop the in-memory copy so the next read goes back to disk."""
    global _catalog
    with _lock:
        _catalog = None


def _save() -> None:
    """Atomic write — a crash or a concurrent reader never sees half a file."""
    with _lock:
        if not _writable or _catalog is None:
            return
        path = OEM_CATALOG_PATH
        folder = os.path.dirname(os.path.abspath(path))
        os.makedirs(folder, exist_ok=True)
        fd, tmp = tempfile.mkstemp(prefix=".oem_catalog_", suffix=".json", dir=folder)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump(_catalog, f, indent=2, sort_keys=True, ensure_ascii=False)
                f.write("\n")
            os.replace(tmp, path)
        except Exception:
            try:
                os.remove(tmp)
            except OSError:
                pass


def vehicle_key(vehicle: str) -> str:
    from services.price_lookup import _vehicle_query_name
    return _vehicle_query_name(vehicle or "").strip().lower()


def _display_name(vehicle: str) -> str:
    from services.price_lookup import _vehicle_query_name
    return _vehicle_query_name(vehicle or "").strip()


def _parse_ts(value) -> Optional[datetime]:
    if not value:
        return None
    try:
        dt = datetime.fromisoformat(str(value))
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=_IST)


def format_ts(ts) -> str:
    """Epoch seconds or datetime -> ISO-8601 in IST, the catalogue's date format."""
    if isinstance(ts, datetime):
        dt = ts if ts.tzinfo else ts.replace(tzinfo=_IST)
    else:
        dt = datetime.fromtimestamp(float(ts), _IST)
    return dt.astimezone(_IST).isoformat(timespec="seconds")


def _now() -> datetime:
    return datetime.now(_IST)


def get(vehicle: str, part: str, now: Optional[datetime] = None) -> Optional[dict]:
    """The priced catalogue entry for this vehicle/part, or None.

    None when the vehicle or part is absent, or recorded as unpriced — the
    caller treats all three the same way (go to the live API). A priced entry
    comes back with `stale` set when it is older than the TTL, or when its
    fetch date is missing/unreadable (an undated price cannot prove it is fresh).
    """
    cat = _load()
    with _lock:
        entry = ((cat["vehicles"].get(vehicle_key(vehicle)) or {})
                 .get("parts", {}).get((part or "").strip().lower()))
        entry = copy.deepcopy(entry) if entry else None
    if not entry or not entry.get("price"):
        return None

    fetched = _parse_ts(entry.get("fetched_on"))
    ttl_days = OEM_CATALOG_TTL_DAYS
    if fetched is None:
        age_days, stale = None, True
    else:
        age_days = ((now or _now()) - fetched).total_seconds() / 86400
        stale = age_days > ttl_days
    price = int(entry["price"])
    return {
        "price": price,
        "low": int(entry.get("low") or price),
        "high": int(entry.get("high") or price),
        "sources": list(entry.get("sources") or []),
        "source_count": int(entry.get("source_count") or len(entry.get("sources") or [])),
        "providers": list(entry.get("providers") or []),
        "fetched_on": entry.get("fetched_on"),
        "age_days": round(age_days, 1) if age_days is not None else None,
        "stale": stale,
        "ttl_days": ttl_days,
    }


def upsert(vehicle: str, part: str, hit: Optional[dict], fetched_at=None,
           origin: str = "runtime") -> None:
    """Record an API result for this vehicle/part and save.

    `hit` is price_lookup.lookup_market_price()'s return value. A None hit (the
    API could not corroborate a price) is recorded as unpriced ONLY when there is
    no priced entry already: a failed refresh must never erase the stale price
    the caller is about to fall back on.
    """
    vkey = vehicle_key(vehicle)
    pkey = (part or "").strip().lower()
    if not vkey or not pkey:
        return
    stamp = format_ts(fetched_at if fetched_at is not None else _now())

    cat = _load()
    with _lock:
        veh = cat["vehicles"].setdefault(
            vkey, {"display_name": _display_name(vehicle), "parts": {}})
        parts = veh.setdefault("parts", {})
        if hit and hit.get("price"):
            domains = list(hit.get("domains") or [])
            parts[pkey] = {
                "price": int(hit["price"]),
                "low": int(hit.get("low") or hit["price"]),
                "high": int(hit.get("high") or hit["price"]),
                "currency": "INR",
                "fetched_on": stamp,
                "sources": domains,
                "source_count": int(hit.get("sources") or len(domains)),
                "providers": list(hit.get("providers") or []),
                "origin": origin,
            }
        else:
            existing = parts.get(pkey) or {}
            if existing.get("price"):
                return
            parts[pkey] = {"price": None, "status": "unpriced",
                           "fetched_on": stamp, "origin": origin}
        _save()


def snapshot() -> dict:
    """A deep copy of the whole catalogue — for scripts and sanity checks."""
    cat = _load()
    with _lock:
        return copy.deepcopy(cat)
