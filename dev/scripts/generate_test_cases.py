# ── Generic Garage Estimate template ──────────────────────────────────────────
def generate_estimate(out_path: Path, *, workshop_name: str, workshop_address: str,
                       workshop_phone: str, gstin: str, job_card_no: str, date_str: str,
                       customer_name: str, vehicle: str, reg_no: str, odometer: str,
                       policy_no: str, rows: list[tuple[str, str, str, str, int]],
                       note: str, dealer_footer: str, demo_note: str = "",
                       chassis_no: str = "", service_advisor: str = "",
                       claim_no: str = "", surveyor: str = ""):
    """Render one repair estimate.

    Realism notes, all of which the pipeline actually consumes or an assessor
    would actually look for:
      * labour rows carry hours x rate rather than a lump sum with Qty 1 —
        services/labour_engine assesses hours x rate and compares against these
        lines, so a lump sum meant that comparison never exercised;
      * the chassis/VIN and the insurer + claim + surveyor block are on every
        real insurance-facing job card and were absent here;
      * the signatory is a named service advisor, not the workshop's own name.
    """
    pdf = FPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    pdf.set_fill_color(*DARK_BLUE)
    pdf.rect(0, 0, 210, 20, style="F")
    pdf.set_xy(0, 4)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 7, _s(workshop_name), align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 8)
    pdf.set_x(0)
    pdf.cell(0, 6, _s(f"{workshop_address} | Ph: {workshop_phone} | GSTIN: {gstin}"),
             align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.set_y(26)

    pdf.set_fill_color(*LIGHT_BLUE_BG)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 10, "VEHICLE REPAIR ESTIMATION SLIP", align="C", fill=True, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)

    pdf.set_font("Helvetica", "", 9)
    pdf.cell(95, 6, _s(f"Job Card No.: {job_card_no}"), border=1)
    pdf.cell(95, 6, _s(f"Date: {date_str}"), border=1, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)

    _section_bar(pdf, "CUSTOMER & VEHICLE DETAILS", DARK_BLUE)
    _field(pdf, "Customer Name:", customer_name)
    _field(pdf, "Vehicle:", vehicle)
    _field(pdf, "Registration No.:", reg_no)
    _field(pdf, "Odometer Reading:", odometer)
    if chassis_no:
        _field(pdf, "Chassis No. (VIN):", chassis_no)
    _field(pdf, "Insurer / Policy No.:", f"Ganit Motors Insurance Co. Ltd. / {policy_no}")
    if claim_no or surveyor:
        _field(pdf, "Claim No. / Surveyor:",
               " | ".join(x for x in (claim_no, surveyor) if x))
    pdf.ln(2)

    subtotal = sum(r[4] for r in rows)
    cgst = round(subtotal * CGST_RATE)
    sgst = round(subtotal * SGST_RATE)
    grand_total = subtotal + cgst + sgst

    with pdf.table(
        col_widths=(3.5, 8.5, 3.2, 1.6, 2.2, 3.0),
        text_align=("LEFT", "LEFT", "CENTER", "CENTER", "CENTER", "RIGHT"),
    ) as table:
        header = table.row()
        for h in ("#", "Part / Service Description", "Work Type", "Qty", "Source", "Amount (Rs.)"):
            header.cell(_s(h))
        for i, (desc, wtype, qty, src, amt) in enumerate(rows, start=1):
            row = table.row()
            row.cell(str(i))
            row.cell(_s(desc))
            row.cell(_s(wtype))
            row.cell(qty)
            row.cell(_s(src))
            row.cell(f"{amt:,}")

    pdf.ln(2)
    pdf.set_font("Helvetica", "", 10)
    for label, val in [("Sub-Total", subtotal), ("CGST @ 9%", cgst), ("SGST @ 9%", sgst)]:
        pdf.cell(160, 6, _s(label), border=1, align="R")
        pdf.cell(30, 6, f"Rs. {val:,}", border=1, align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_fill_color(*LIGHT_BLUE_BG)
    pdf.cell(160, 8, "GRAND TOTAL", border=1, align="R", fill=True)
    pdf.cell(30, 8, f"Rs. {grand_total:,}", border=1, align="R", fill=True, new_x="LMARGIN", new_y="NEXT")

    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 8)
    pdf.multi_cell(0, 5, _s(f"Note: {note}"))

    if demo_note:
        pdf.ln(1)
        pdf.set_font("Helvetica", "BI", 7.5)
        pdf.set_text_color(180, 40, 40)
        pdf.multi_cell(0, 4, _s(demo_note))
        pdf.set_text_color(0, 0, 0)

    pdf.ln(6)
    advisor = service_advisor or "R. Krishnan, Service Advisor"
    pdf.set_font("Helvetica", "I", 10)
    pdf.cell(95, 6, _s(f"Sd/- {customer_name}"), align="C")
    pdf.cell(95, 6, _s(f"Sd/- {advisor.split(',')[0]}"), align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 8)
    pdf.cell(95, 5, "Customer Signature", align="C")
    pdf.cell(95, 5, "Authorised Signatory", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "I", 8)
    pdf.cell(95, 5, _s(f"({customer_name})"), align="C")
    pdf.cell(95, 5, _s(f"({advisor})"), align="C", new_x="LMARGIN", new_y="NEXT")

    # Footer block: auto page-break OFF while writing it, or the second line
    # crosses the bottom margin and fpdf2 spawns an extra page carrying nothing
    # but the specimen notice.
    pdf.set_auto_page_break(auto=False)
    pdf.set_y(-17)
    pdf.set_font("Helvetica", "I", 7)
    pdf.set_text_color(*GREY_TEXT)
    pdf.cell(0, 4.5, _s(dealer_footer), align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "I", 6.5)
    pdf.cell(0, 4, _s(SPECIMEN_LINE), align="C")
    pdf.set_auto_page_break(auto=True, margin=15)

    pdf.set_subject("SYNTHETIC SPECIMEN - ClaimIntel demonstration document")
    pdf.set_author("ClaimIntel demo fixture generator")
    pdf.output(str(out_path))
    print(f"Wrote {out_path}  (Grand Total Rs. {grand_total:,})")


# ── Demo-autofill manifest ────────────────────────────────────────────────────
# Powers the one-click showcase buttons on the New Claim page (served by
# backend/services/demo_cases.py via GET /api/demo/cases).
#
# Written HERE, by the same run that writes the PDFs, on purpose. Every value a
# button needs already moves under this script's feet: incident dates are
# computed from `ref`, and the estimate totals are row-sums that get
# recalibrated whenever live pricing drifts (case 1's README has been wrong
# about its amount before, for exactly that reason). A hand-maintained copy in
# JSON or in React would go stale silently and put a presenter on stage with a
# form that contradicts the PDF they just uploaded.
#
# Dates are stored as `incident_days_ago` OFFSETS, not absolute dates, so the
# manifest also survives the gap between generator runs — the backend resolves
# them against date.today() when the button is clicked.
DEMO_MANIFEST_PATH = ROOT / "data" / "config" / "demo_cases.json"


def _demo_entry(*, case_id: str, label: str, vehicle_short: str, expected: str,
                headline: str, policy: dict, days_ago: int, incident_time: str,
                location: str, description: str, fir_number: str,
                workshop_name: str, estimate_amount: int, folder: str,
                files: list[tuple[str, str, str, str]]) -> dict:
    """One case's row in demo_cases.json.

    `files` is (key, filename_on_disk, serve_as, doc_type). `serve_as` exists
    because case 2's damage photos are AI-generated and one still carries its
    Gemini default filename — uploading that verbatim trips FC-28 (30 points),
    which would push case 2 out of Escalate into Reject. Its own README already
    tells presenters to rename before uploading by hand; the button does it for
    them. `doc_type` must be one of the upload endpoint's whitelisted values.

    `expected` is recorded for developers and for data_sanity, and is
    deliberately NOT displayed on the New Claim page — printing the verdict on
    the intake screen before any agent has run pre-announces the answer to the
    room. `headline` follows the same rule: it describes the EVIDENCE (what
    happened, what is attached), never the conclusion. "Staged collision" and
    "write-off inflation" are findings the pipeline produces, so they do not
    belong on a button that is clicked before the pipeline runs.
    """
    return {
        "id": case_id,
        "label": label,
        "vehicle": vehicle_short,
        "expected": expected,
        "headline": headline,
        "phone": policy["phone"],
        "policy_no": policy["policy_no"],
        "claim_type": "Motor - Own Damage",
        "incident_days_ago": days_ago,
        "incident_time": incident_time,
        "incident_location": location,
        "description": description,
        "fir_number": fir_number,
        "workshop_name": workshop_name,
        "estimate_amount": estimate_amount,
        "folder": folder,
        "files": [
            {"key": k, "filename": fn, "serve_as": sa, "doc_type": dt}
            for k, fn, sa, dt in files
        ],
    }


def write_demo_manifest(entries: list[dict]) -> None:
    """Dump the collected case entries to data/config/demo_cases.json."""
    entries = [e for e in entries if e]
    payload = {
        "version": "1.0",
        "description": (
            "Demo-autofill manifest for the New Claim page's one-click showcase buttons. "
            "GENERATED by dev/scripts/generate_test_cases.py — do not hand-edit; re-run the "
            "generator instead. Incident dates are day-offsets resolved against today at "
            "request time, so this file does not go stale between runs. Read by "
            "backend/services/demo_cases.py."
        ),
        "generated_from": "dev/scripts/generate_test_cases.py",
        "cases": entries,
    }
    DEMO_MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(DEMO_MANIFEST_PATH, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    missing = [
        f"{e['folder']}/{f['filename']}"
        for e in entries for f in e["files"]
        if not (TEST_DIR / e["folder"] / f["filename"]).exists()
    ]
    print(f"\nWrote {DEMO_MANIFEST_PATH.relative_to(ROOT)}  "
          f"({len(entries)} demo cases for the New Claim quick-fill buttons)")
    if missing:
        # Not a failure: the damage photos are gitignored (test/**/*.jpg|png|mp4),
        # so a fresh clone legitimately has the PDFs and none of the images. The
        # picker attaches what exists and tells the presenter what to add by hand.
        print(f"  NOTE: {len(missing)} fixture file(s) not on disk — the demo button will "
              f"attach the rest and flag these:")
        for m in missing:
            print(f"    - {m}")


